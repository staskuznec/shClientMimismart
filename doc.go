// Package shclient — клиент протокола SHS умного дома MimiSmart.
//
// Клиент подключается к серверу по TCP, проходит авторизацию по ключу AES и
// отправляет значения: текстовые статусы, показания датчиков, однобайтовые
// состояния и произвольные полезные нагрузки.
//
// # Использование
//
//	c, err := shclient.New("192.168.1.10:9001", "0123456789abcdef")
//	if err != nil {
//		return err
//	}
//	if err := c.Connect(ctx); err != nil {
//		return err
//	}
//	defer c.Close()
//
//	// Конструкторы только собирают значения и проверяют их представимость.
//	temp, err := shclient.Sensor(100, 0, 23.5) // элемент 100, подэлемент 0
//	if err != nil {
//		return err
//	}
//	note, err := shclient.Text(100, 1, "норма") // элемент 100, подэлемент 1
//	if err != nil {
//		return err
//	}
//
//	// Отправка — только здесь. Оба значения уходят одним батчем,
//	// каждое на свой адрес; одно не является запасным для другого.
//	if err := c.Send(ctx, temp, note); err != nil {
//		return err
//	}
//
// # Какое значение чему соответствует
//
// Форма значения задаётся элементом, а не удобством вызывающего кода:
//
//   - [Sensor] — показание датчика, два байта fixed-point 8.8;
//   - [Text] — текстовый статус;
//   - [Byte] — один байт: лампа, скрипт, клапан, шторы, ворота, датчики двери
//     и протечки;
//   - [Raw] — произвольные байты, если раскладка элемента не сводится
//     к предыдущим.
//
// Перепутать [Sensor] и [Byte] особенно легко, а последствия неочевидны:
// единица у датчика упакуется как 00 01, однобайтовый элемент прочитает из неё
// нулевой младший байт и останется выключенным. Выключение при этом сработает,
// потому что ноль даёт нули в обоих байтах, — и выглядит это как статус,
// пропадающий через раз.
//
// # Два вида ошибок
//
// Ошибка от [Sensor] или [Text] — это ошибка сборки значения: оно не
// представимо в протоколе ([ErrValueOutOfRange], [ErrPayloadTooLarge]).
// Сеть при этом не задействована, повторять отправку бессмысленно —
// значение нужно масштабировать или укоротить. У [Byte] такой ошибки нет
// вовсе: один байт помещается в пакет всегда.
//
// Ошибка от [Client.Send] — это ошибка передачи: обрыв, таймаут, отменённый
// контекст, [ErrNotConnected]. Вот её имеет смысл ретраить.
//
// # Формат обмена
//
// Соединение начинается с авторизации: сервер присылает 16 байт challenge,
// клиент шифрует их одним блоком AES на ключе и отправляет обратно. Затем
// клиент шлёт XML-запрос get-shc и получает ответ shcxml, из которого
// вычисляется идентификатор клиента, проставляемый во все дальнейшие пакеты.
//
// Пакет значения состоит из 10-байтового заголовка (все многобайтовые поля —
// little-endian) и полезной нагрузки:
//
//	смещение  размер  поле
//	0         2       client id
//	2         2       id элемента
//	4         1       PD (код команды)
//	5         1       0
//	6         1       0
//	7         1       subid
//	8         2       длина полезной нагрузки
//	10        N       полезная нагрузка
//
// # Описание дома
//
// В ответе на рукопожатие сервер присылает logic.xml — дерево областей с
// элементами, их адресами, именами и типами. По умолчанию клиент его
// отбрасывает; чтобы получить, задайте приёмник через [WithLogicSink].
// Отдаются сырые байты: разбор XML — дело вызывающего кода.
//
// Состояния элементов можно запросить у сервера через [Client.RequestAll].
// Ответ приходит пакетами [PDPingModule], которые эта версия клиента не
// разбирает.
//
// # Диапазон значений датчиков
//
// Показание датчика передаётся как fixed-point 8.8: uint16(v*256). Значения
// вне диапазона [SensorMin, SensorMax] представить нельзя, поэтому [Sensor]
// возвращает [ErrValueOutOfRange], а не портит данные молча. Величины, выходящие
// за диапазон (мощность в ваттах, отрицательные токи), нужно масштабировать или
// смещать на стороне вызывающего кода.
